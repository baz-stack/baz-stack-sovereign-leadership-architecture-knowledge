#!/usr/bin/env python3
"""Stage the private repository locally (nothing is pushed anywhere).

Usage: python3 -I tools/stage_private_repo.py <empty-target-directory>

Layout of the staged repository: the contents of ./restricted at its root (so it can be cloned back
into the public working copy as ./restricted for full validation), plus legacy-public-history/ holding
the files classified private-migrate in registry/repository-classification.yaml at their original paths.
Writes MIGRATION_MANIFEST.yaml (SHA-256 for every staged file), README.md, CLAUDE.md and .gitignore,
then makes one local git commit.
"""
import hashlib
import shutil
import subprocess
import sys
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parent.parent
EXCLUDE = {"Sovereign_Knowledge_OS_RESTRICTED_BUNDLE.zip", "Sovereign_Private_Repo_Staging.zip", "__pycache__"}


def sha(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()


def main():
    target = Path(sys.argv[1]).resolve()
    if target.exists() and any(target.iterdir()):
        sys.exit("target must be empty or absent")
    target.mkdir(parents=True, exist_ok=True)
    src = ROOT / "restricted"
    for p in sorted(src.rglob("*")):
        rel = p.relative_to(src)
        if any(part in EXCLUDE for part in rel.parts) or not p.is_file():
            continue
        (target / rel).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(p, target / rel)
    cls = yaml.safe_load((ROOT / "registry" / "repository-classification.yaml").read_text(encoding="utf-8"))
    head = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip()
    migrate = [r["path"] for r in cls["files"] if r["class"] == "private-migrate"]
    split = [r["path"] for r in cls["files"] if r["class"] == "split-public-summary"]
    for rel in migrate:
        dest = target / "legacy-public-history" / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(subprocess.check_output(["git", "show", f"HEAD:{rel}"], cwd=ROOT))
    for rel in split:  # originals come from the base commit, before any summarizing edit
        dest = target / "legacy-public-history" / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(subprocess.check_output(["git", "show", f"358a857:{rel}"], cwd=ROOT))
    (target / ".gitignore").write_text(".DS_Store\n*.tmp\n__pycache__/\n.env\n.env.*\n*.pem\n*.key\n", encoding="utf-8")
    (target / "README.md").write_text(
        "# Sovereign Leadership: private repository\n\n"
        "Confidential intellectual property and operational materials for Baz Porter LLC. **Never make this repository public.**\n\n"
        "- Companion public repository: `baz-stack/sovereign-leadership-architecture` (AI-readable research and evidence).\n"
        "- Layout: the root mirrors the public repository's gitignored `restricted/` folder. Clone this repository into the public working copy as `restricted/` to run `python3 -I tools/validate.py --full`.\n"
        "- `legacy-public-history/` holds files that were once in the public repository (original paths preserved) and were moved here after classification (`registry/repository-classification.yaml` in the public repository).\n"
        "- `MIGRATION_MANIFEST.yaml` lists every staged file with its SHA-256.\n"
        "- Credentials, tokens and passwords never go in this repository either. Use the approved secret store.\n", encoding="utf-8")
    (target / "CLAUDE.md").write_text(
        "# Instructions for agents (private repository)\n\n"
        "1. This repository is private and confidential. Do not copy its contents into the public repository, a public page, a third-party tool or a prompt for an external service.\n"
        "2. Source precedence: founder decisions, Rosetta Stone v4.2, the 2026-10-14 ICA, current product specifications, then everything else.\n"
        "3. Do not edit Rosetta Stone v4.2 or the ICA. Do not change prices, promises or launch status without founder approval.\n"
        "4. Public projections are generated by `tools/build_projections.py` in the public repository from `data/`. Edit data here, rebuild there.\n"
        "5. Do not rewrite history, delete evidence or push without the owner's approval.\n", encoding="utf-8")
    entries = []
    for p in sorted(target.rglob("*")):
        if p.is_file() and ".git" not in p.relative_to(target).parts and p.name != "MIGRATION_MANIFEST.yaml":
            entries.append({"path": str(p.relative_to(target)), "sha256": sha(p), "bytes": p.stat().st_size})
    manifest = {"manifest": "private-repository-staging", "generated": "2026-10-17", "public_repo_commit": head,
                "files": len(entries), "legacy_public_history_files": len(migrate) + len(split), "entries": entries}
    (target / "MIGRATION_MANIFEST.yaml").write_text(yaml.safe_dump(manifest, sort_keys=False, allow_unicode=True, width=120), encoding="utf-8")
    subprocess.check_call(["git", "init", "-q", "-b", "main"], cwd=target)
    subprocess.check_call(["git", "add", "-A"], cwd=target)
    subprocess.check_call(["git", "-c", "user.name=Baz Porter LLC", "-c", "user.email=ask@bazporter.com", "commit", "-q", "-m", "Stage private repository from the public repository restricted store and classified files"], cwd=target)
    print(f"staged {len(entries)} files at {target}; legacy-public-history files: {len(migrate) + len(split)}")


if __name__ == "__main__":
    main()
